// What each byte 0x80-0xFF means in the legacy single-byte encodings a supplier export may use. They are spelled out here
// instead of relying on TextDecoder, because the browser and Node disagree on labels like "windows-1252" (Node's ICU
// treats it as ISO-8859-1 and turns 0x80 into a control character instead of the euro sign), and a paywalled product must
// not depend on which JavaScript runtime parses the file. Bytes 0x00-0x7F are ASCII in all of them.
//
// Following the WHATWG Encoding Standard, the few bytes a code page leaves unassigned (for example 0x81 in windows-1252)
// stay as the C1 control character with the same number, which the encoding detector treats as strong evidence AGAINST
// that code page. single-byte-tables.test.ts checks every table against the runtime's own TextDecoder where it is right.

